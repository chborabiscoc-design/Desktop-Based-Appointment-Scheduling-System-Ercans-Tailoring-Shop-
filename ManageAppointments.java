    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed


    int row = jTable1.getSelectedRow();

    if (row == -1) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Please select an appointment first."
        );
        return;
    }

    int appointmentId = Integer.parseInt(
        jTable1.getValueAt(row, 0).toString()
    );

    String displayedStatus =
        jTable1.getValueAt(row, 6).toString();

    String sql;
    String message;

    if (displayedStatus.equalsIgnoreCase("Cancellation Pending")) {

        sql = "UPDATE appointments "
            + "SET appointment_status = 'Cancelled', "
            + "cancellation_status = 'Approved' "
            + "WHERE appointment_id = ? "
            + "AND cancellation_status = 'Pending'";

        message = "Cancellation approved. Appointment cancelled.";

    } else {

        sql = "UPDATE appointments "
            + "SET appointment_status = 'Accepted' "
            + "WHERE appointment_id = ? "
            + "AND appointment_status = 'Pending'";

        message = "Appointment accepted!";
    }

    try (
        java.sql.Connection con = DBConnection.getConnection();
        java.sql.PreparedStatement pst = con.prepareStatement(sql)
    ) {
        pst.setInt(1, appointmentId);

        int updated = pst.executeUpdate();

        javax.swing.JOptionPane.showMessageDialog(
            this,
            updated > 0 ? message : "Request could not be updated."
        );

        loadAppointments();

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Database error: " + e.getMessage()
        );
    }

    }//GEN-LAST:event_jButton1ActionPerformed

