private void loadAppointments() {
    String sql = "SELECT a.appointment_id, "
        + "CONCAT(c.first_name, ' ', c.last_name) AS customer, "
        + "a.appointment_date, a.appointment_time, "
        + "s.service_name, a.details, a.appointment_status, "
        + "a.cancellation_status "
        + "FROM appointments a "
        + "INNER JOIN customers c ON a.customer_id = c.customer_id "
        + "INNER JOIN Service s ON a.service_id = s.service_id "
        + "WHERE a.appointment_status = 'Pending' "
        + "OR a.cancellation_status = 'Pending' "
        + "ORDER BY a.created_at DESC";

    try (
        java.sql.Connection con = DBConnection.getConnection();
        java.sql.PreparedStatement pst = con.prepareStatement(sql);
        java.sql.ResultSet rs = pst.executeQuery()
    ) {

        javax.swing.table.DefaultTableModel model =
            (javax.swing.table.DefaultTableModel) jTable1.getModel();

        model.setRowCount(0);

        int count = 0;

        while (rs.next()) {

            String status = rs.getString("appointment_status");

            if ("Pending".equalsIgnoreCase(
                    rs.getString("cancellation_status"))) {
                status = "Cancellation Pending";
            }

            model.addRow(new Object[] {
                rs.getInt("appointment_id"),
                rs.getString("customer"),
                rs.getString("appointment_date"),
                rs.getString("appointment_time"),
                rs.getString("service_name"),
                rs.getString("details"),
                status
            });

            count++;
        }

        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Appointments loaded: " + count
        );

    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Failed to load appointments: " + e.getMessage()
        );
        e.printStackTrace();
    }

    

}
