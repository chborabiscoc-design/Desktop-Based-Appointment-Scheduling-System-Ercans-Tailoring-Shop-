    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
                                       

    String date = jTextField1.getText().trim();
    String time = (String) jComboBox1.getSelectedItem();
    String selectedService = (String) jComboBox2.getSelectedItem();
    String details = jTextField2.getText().trim();

    if (date.isEmpty() || details.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Please fill in the appointment date and tailoring details."
        );
        return;
    }

    if (selectedService == null) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "No tailoring services available. Please check the Service table."
        );
        return;
    }

   java.time.LocalDate appointmentDate;

try {
    appointmentDate = java.time.LocalDate.parse(
        date,
        java.time.format.DateTimeFormatter.ofPattern(
            "MMMM d, yyyy",
            java.util.Locale.ENGLISH
        )
    );
} catch (java.time.format.DateTimeParseException e) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Please enter the date in Month Day, Year format.\n"
        + "Example: October 20, 2026"
    );
    return;
}

    int serviceId;

    try {
        serviceId = Integer.parseInt(
            selectedService.substring(0, selectedService.indexOf(" - "))
        );
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Invalid service selection. Please select a service again."
        );
        return;
    }

    String sql = "INSERT INTO appointments "
            + "(customer_id, service_id, appointment_date, "
            + "appointment_time, details, appointment_status, work_status) "
            + "VALUES (?, ?, ?, ?, ?, 'Pending', 'Not Started')";

    try (
        java.sql.Connection con = DBConnection.getConnection();
        java.sql.PreparedStatement pst = con.prepareStatement(sql)
    ) {
        pst.setInt(1, customerId);
        pst.setInt(2, serviceId);
        pst.setDate(3, java.sql.Date.valueOf(appointmentDate));

        java.time.LocalTime appointmentTime =
            java.time.LocalTime.parse(
                time,
                java.time.format.DateTimeFormatter.ofPattern(
                    "h:mm a",
                    java.util.Locale.ENGLISH
                )
            );

        pst.setTime(4, java.sql.Time.valueOf(appointmentTime));
        pst.setString(5, details);

        pst.executeUpdate();

        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Appointment submitted successfully!\n"
            + "Waiting for admin approval."
        );

        AppointmentSubmitted submitted =
            new AppointmentSubmitted(firstName, lastName, customerId);

        submitted.setVisible(true);
        this.dispose();

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Failed to submit appointment: " + e.getMessage()
        );
    }


    }//GEN-LAST:event_jButton2ActionPerformed

