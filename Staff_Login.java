    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed


    String username = jTextField1.getText().trim();
    String password = new String(jPasswordField1.getPassword());

    if (username.isEmpty() || password.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Please enter your username and password."
        );
        return;
    }

    String sql = "SELECT staff_id, first_name, last_name, status "
           + "FROM staff WHERE username = ? AND password = ?";

    try (
        java.sql.Connection con = DBConnection.getConnection();
        java.sql.PreparedStatement pst = con.prepareStatement(sql)
    ) {
        pst.setString(1, username);
        pst.setString(2, password);

        try (java.sql.ResultSet rs = pst.executeQuery()) {

            if (rs.next()) {

               String status = rs.getString("status");

if (!"Approved".equalsIgnoreCase(status)) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Your account is still pending admin approval."
    );
    return;
}
                int staffId = rs.getInt("staff_id");
                String firstName = rs.getString("first_name");
                String lastName = rs.getString("last_name");

                StaffDashboard dashboard =
                    new StaffDashboard(staffId, firstName, lastName);

                dashboard.setVisible(true);
                this.dispose();

            } else {
                javax.swing.JOptionPane.showMessageDialog(
                    this, "Invalid username or password."
                );
            }
        }

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Login failed: " + e.getMessage()
        );
    }

    }//GEN-LAST:event_jButton2ActionPerformed

