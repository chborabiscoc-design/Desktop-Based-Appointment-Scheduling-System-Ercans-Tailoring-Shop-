    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
    
int row = jTable1.getSelectedRow();

if (row == -1) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "Please select a staff member.");
    return;
}

int staffId = Integer.parseInt(
        jTable1.getValueAt(row, 0).toString());

String sql = "UPDATE staff SET status = 'Approved' "
        + "WHERE staff_id = ? AND status = 'Pending'";

try (java.sql.Connection con = DBConnection.getConnection()) {
    if (con == null) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "Cannot connect to the database.");
        return;
    }

    try (java.sql.PreparedStatement pst = con.prepareStatement(sql)) {
        pst.setInt(1, staffId);
        int updated = pst.executeUpdate();

        if (updated > 0) {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "Staff account approved!");
        } else {
            javax.swing.JOptionPane.showMessageDialog(
                    this, "This account is not pending approval.");
        }
    }

    loadStaff();

} catch (java.sql.SQLException e) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "Approval failed: " + e.getMessage());
}
    }//GEN-LAST:event_jButton4ActionPerformed

